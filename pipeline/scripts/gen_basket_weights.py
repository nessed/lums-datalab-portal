"""Generate specs/cpi_basket_weights.yaml from the built CPI dataset. Numbers are copied by code, never typed.

A weight is recorded only when every issue that prints it (in a table that is not flagged and whose
weights add to 100) prints the same figure, and at least two issues print it.
"""
from collections import defaultdict
from pathlib import Path

from datalab import config
from datalab.datasets.common import load_dataset
from datalab.schema import PASSING

d = load_dataset("cpi")
ok_cells = set()
for chk in d["checks"]:
    if chk.check_type == "weights_sum" and chk.result in PASSING:
        ok_cells |= {chk.target_cell_id, *chk.member_cell_ids}
seen = defaultdict(dict)       # (base tag, area, group) -> {source_id: value_raw}
for c in d["cells"]:
    sid = c.series_id or ""
    parts = sid.split(".")
    # cpi.<area>.weight.<slug>.<base tag>, or cpi.weight.<slug>.<base tag> where the document states no area (D27)
    if len(parts) == 4 and parts[:2] == ["cpi", "weight"]:
        parts = ["cpi", "not_stated", "weight", parts[2], parts[3]]
    if len(parts) == 5 and parts[0] == "cpi" and parts[2] == "weight" and c.cell_id in ok_cells and not c.structural_flags \
            and c.value_parsed is not None:
        seen[(parts[4], parts[1], parts[3])][c.source_id] = c.value_parsed
lines = ["# CPI basket weights by base year, area and group. GENERATED by code",
         "# (pipeline/scripts/gen_basket_weights.py) from the Monthly Review issues themselves: a weight is",
         "# listed only when at least two issues print it, in tables whose weights add to 100, and every one",
         "# of them prints the same figure. Used only as the expected value of the check",
         "# `cpi.weight_is_the_groups_basket_weight` (does a row's weight match the group it is labelled",
         "# as?). Never published from here. To confirm against the PBS methodology note.",
         "weights:"]
skipped = []
for (tag, area, group), by_src in sorted(seen.items()):
    values = set(by_src.values())
    if len(values) == 1 and len(by_src) >= 2:
        base_year = tag[1:].replace("_", "-")
        lines.append(f'  - {{base_year: "{base_year}", area: {area}, group: {group}, weight: "{values.pop()}", issues: {len(by_src)}}}')
    else:
        skipped.append((tag, area, group, dict(by_src)))
out = config.SPECS_DIR / "cpi_basket_weights.yaml"
out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(len(lines) - 7, "weights written;", len(skipped), "skipped")
for s in skipped:
    print("  skipped", s)
